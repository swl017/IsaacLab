"""Visual validation: triangulation covariance vs Monte Carlo.

Produces a small report of figures that show the analytical Sigma_X computed
by `compute_triangulation_covariance` agrees with Monte Carlo statistics
generated by perturbing camera intrinsics around their nominal values and
re-triangulating with the nominal K.

Plots written under tests/mc_plots/intrinsic_cov/:
  1. cov_projections.png    — XY/XZ/YZ MC scatter with analytic 1σ/2σ/3σ ellipses
  2. marginal_histograms.png — per-axis MC histograms with analytic Gaussian PDF
  3. nees_chi2.png          — Mahalanobis² histogram vs chi²(3) reference
  4. zoom_sweep.png         — trace(Σ_X) analytic vs MC across zoom commands
  5. matrix_compare.png     — matrix heatmap of empirical vs analytic Σ_X
"""

